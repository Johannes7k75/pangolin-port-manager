package docker

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"pangolin-port-manager/internal/config"
	"pangolin-port-manager/internal/models"
)

// GenerateComposeYAML produces the formatted docker-compose.ports.yml content
func GenerateComposeYAML(rules []models.PortRule, cfg *config.Config) string {
	var active []models.PortRule
	for _, r := range rules {
		if r.Enabled {
			active = append(active, r)
		}
	}

	sort.Slice(active, func(i, j int) bool {
		if active[i].Port == active[j].Port {
			return active[i].Protocol < active[j].Protocol
		}
		return active[i].Port < active[j].Port
	})

	var b strings.Builder
	b.WriteString("# Generated by Pangolin Port Manager. DO NOT EDIT DIRECTLY.\n")
	b.WriteString("services:\n")

	// Gerbil Service (Hosts published ports)
	b.WriteString(fmt.Sprintf("  %s:\n", cfg.GerbilServiceName))
	if len(active) > 0 {
		b.WriteString("    ports:\n")
		for _, r := range active {
			b.WriteString(fmt.Sprintf("      - \"%d:%d/%s\"\n", r.Port, r.Port, r.Protocol))
		}
	} else {
		b.WriteString("    ports: []\n")
	}

	b.WriteString("\n")

	// Traefik Service (EntryPoints command flags)
	b.WriteString(fmt.Sprintf("  %s:\n", cfg.TraefikServiceName))
	b.WriteString("    command:\n")
	for _, cmd := range cfg.TraefikBaseCommands {
		b.WriteString(fmt.Sprintf("      - %q\n", cmd))
	}
	for _, r := range active {
		epName := fmt.Sprintf("%s-%d", r.Protocol, r.Port)
		epFlag := fmt.Sprintf("--entryPoints.%s.address=:%d/%s", epName, r.Port, r.Protocol)
		b.WriteString(fmt.Sprintf("      - %q\n", epFlag))
	}

	return b.String()
}

// WriteComposeFile atomically writes the generated compose content to the target path
func WriteComposeFile(rules []models.PortRule, cfg *config.Config) error {
	content := GenerateComposeYAML(rules, cfg)
	targetPath := cfg.ComposeOutPath

	dir := filepath.Dir(targetPath)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}

	tmpFile := targetPath + ".tmp"
	if err := os.WriteFile(tmpFile, []byte(content), 0644); err != nil {
		return err
	}

	return os.Rename(tmpFile, targetPath)
}

// HasPendingChanges compares the current file on disk with the expected generated YAML
func HasPendingChanges(rules []models.PortRule, cfg *config.Config) bool {
	cfg.ReloadTraefikBaseCommands()
	existing, err := os.ReadFile(cfg.ComposeOutPath)
	if err != nil {
		// File does not exist yet; if there are rules (or even defaults), treat as pending
		return true
	}

	expected := GenerateComposeYAML(rules, cfg)
	return strings.TrimSpace(string(existing)) != strings.TrimSpace(expected)
}
