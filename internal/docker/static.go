func usesStaticFile(cfg *config.Config) bool {
	for _, arg := range cfg.TraefikBaseCommands {
		if strings.EqualFold(arg, "--configFile") || strings.HasPrefix(strings.ToLower(arg), "--configfile=") {
			return true
		}
	}
	return false
}

func staticSourcePath(cfg *config.Config) string {
	if cfg.TraefikStaticConfigPath != "" {
		return cfg.TraefikStaticConfigPath
	}
	return filepath.Join(cfg.ComposeProjectDir, "config", "traefik", "traefik_config.yml")
}

func mapValue(n *yaml.Node, key string) *yaml.Node {
	for i := 0; i < len(n.Content); i += 2 {
		if strings.EqualFold(n.Content[i].Value, key) {
			return n.Content[i+1]
		}
	}
	return nil
}

// Always derive from the original file: deleting a rule removes only generated
// entry points, while settings owned by the administrator remain untouched.
func generateStaticConfig(rules []models.PortRule, cfg *config.Config) ([]byte, error) {
	source := staticSourcePath(cfg)
	data, err := os.ReadFile(source)
	if err != nil {
		return nil, fmt.Errorf("read Traefik static YAML %q (set TRAEFIK_STATIC_CONFIG_PATH for a custom location): %w", source, err)
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("parse Traefik static YAML: %w", err)
	}
	if len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, fmt.Errorf("Traefik static configuration must be a YAML mapping")
	}
	root := doc.Content[0]
	entryPoints := mapValue(root, "entryPoints")
	if entryPoints == nil {
		entryPoints = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		root.Content = append(root.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: "entryPoints", Tag: "!!str"}, entryPoints)
	}
	if entryPoints.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("Traefik entryPoints must be a YAML mapping")
	}
	// Validate duplicate keys before adding entries.
	var check map[string]interface{}
	if err := doc.Decode(&check); err != nil {
		return nil, fmt.Errorf("invalid Traefik static configuration: %w", err)
	}
	ordered := append([]models.PortRule(nil), rules...)
	sort.Slice(ordered, func(i, j int) bool {
		if ordered[i].Port == ordered[j].Port {
			return ordered[i].Protocol < ordered[j].Protocol
		}
		return ordered[i].Port < ordered[j].Port
	})
	for _, rule := range ordered {
		if !rule.Enabled {
			continue
		}
		name := fmt.Sprintf("%s-%d", rule.Protocol, rule.Port)
		address := fmt.Sprintf(":%d/%s", rule.Port, rule.Protocol)
		if existing := mapValue(entryPoints, name); existing != nil {
			if existing.Kind != yaml.MappingNode {
				return nil, fmt.Errorf("existing Traefik entry point %s must be a mapping", name)
			}
			addr := mapValue(existing, "address")
			if addr == nil || addr.Value != address {
				return nil, fmt.Errorf("existing Traefik entry point %s conflicts with managed address %s", name, address)
			}
			continue
		}
		var entry yaml.Node
		_ = entry.Encode(map[string]string{"address": address})
		entryPoints.Content = append(entryPoints.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: name}, &entry)
	}
	result, err := yaml.Marshal(&doc)
	if err != nil {
		return nil, err
	}
	return append([]byte("# Generated by Pangolin Port Manager. DO NOT EDIT DIRECTLY.\n"), result...), nil
}

func writeAtomic(path string, data []byte, mode os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(path), ".port-manager-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if err := f.Chmod(mode); err != nil {
		f.Close()
		return err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}
